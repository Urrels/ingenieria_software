CREATE PROCEDURE [dbo].[USUARIO_LISTAR_BLOQUEADOS]
AS
    SELECT ID, USUARIO, ROL, INTENTOS_FALLIDOS
    FROM USUARIO
    WHERE BLOQUEADO = 1
    ORDER BY USUARIO
GO

